import json
import typing
from inspect import signature
from typing import Any, Callable, Dict, Iterable, Type, Union

from docstring_parser import parse
from pydantic import BaseModel, create_model
from pydantic.fields import Field, FieldInfo


def create_schema_from_function(
    name: str, func: Callable, injected_args: Iterable[str] | None = None
) -> Type[BaseModel]:
    """Create a pydantic schema from a function's signature."""
    docstr = func.__doc__
    injected = set(injected_args or ())

    docstr = parse(docstr)
    doc_params = {}
    for param in docstr.params:
        doc_params[param.arg_name] = param

    fields = {}
    params = signature(func).parameters
    for param_name in params:
        if param_name in injected:
            continue
        param_type = params[param_name].annotation
        param_default = params[param_name].default
        description = doc_params.get(param_name)
        if description is not None:
            description = description.description
        else:
            description = f"Parameter: {param_name}"

        if typing.get_origin(param_type) is typing.Annotated:
            args = typing.get_args(param_type)
            param_type = args[0]
            if isinstance(args[1], str):
                description = args[1]
            elif isinstance(args[1], FieldInfo):
                description = args[1].description

        if param_type is params[param_name].empty:
            param_type = typing.Any

        if param_default is params[param_name].empty:
            # Required field
            fields[param_name] = (param_type, FieldInfo(description=description))
        elif isinstance(param_default, FieldInfo):
            # Field with pydantic.Field as default value
            fields[param_name] = (param_type, param_default)
        else:
            fields[param_name] = (
                param_type,
                FieldInfo(default=param_default, description=description),
            )

    return create_model(name, **fields)


TYPE_MAPPING: dict[str, type] = {
    "string": str,
    "integer": int,
    "number": float,
    "boolean": bool,
    "object": dict,
    "array": list,
    "null": type(None),
}

CONSTRAINT_MAPPING: dict[str, str] = {
    "minimum": "ge",
    "maximum": "le",
    "exclusiveMinimum": "gt",
    "exclusiveMaximum": "lt",
    "inclusiveMinimum": "ge",
    "inclusiveMaximum": "le",
    "minItems": "min_length",
    "maxItems": "max_length",
}


def __get_field_params_from_field_schema(field_schema: dict) -> dict:
    """Gets Pydantic field parameters from a JSON schema field."""
    field_params = {}
    for constraint, constraint_value in CONSTRAINT_MAPPING.items():
        if constraint in field_schema:
            field_params[constraint_value] = field_schema[constraint]
    if "description" in field_schema:
        field_params["description"] = field_schema["description"]
    if "default" in field_schema:
        field_params["default"] = field_schema["default"]
    return field_params


def create_model_from_schema(name: str, schema: dict) -> type[BaseModel]:
    """Create Pydantic model from a JSON schema generated by
    BaseModel.model_json_schema().
    """
    models: dict[str, type[BaseModel]] = {}
    definitions = schema.get("$defs", {})
    definition_refs = {
        definition: f"_schema_definition_{index}"
        for index, definition in enumerate(definitions)
    }

    def resolve_extra_value_type(value_schema: dict, field_name: str) -> Any:
        """Keep the type and constraints on each additional property's value."""
        value_type = resolve_field_type(value_schema, field_name)
        field_params = __get_field_params_from_field_schema(value_schema)
        # A schema default does not supply missing dictionary entries.
        field_params.pop("default", None)
        if field_params:
            return typing.Annotated[value_type, Field(**field_params)]
        return value_type

    def resolve_field_type(field_schema: dict, field_name: str) -> type[typing.Any]:
        """Resolve scalar, nested-object, array, and dictionary field types."""
        if "$ref" in field_schema:
            model_reference = field_schema["$ref"].split("/")[-1]
            if model_reference in models:
                return models[model_reference]
            if model_reference in definitions:
                # Definition names are JSON keys, not Python expressions.
                return typing.ForwardRef(definition_refs[model_reference])
            return Any

        if "anyOf" in field_schema:
            types = [
                resolve_field_type(option, f"{field_name}_{index}")
                for index, option in enumerate(field_schema["anyOf"])
            ]
            return Union[tuple(types)]  # noqa: UP007

        if field_schema.get("type") == "array":
            item_type = resolve_field_type(
                field_schema.get("items", {}), f"{field_name}_item"
            )
            return list[item_type]  # type: ignore[valid-type]

        if field_schema.get("type") == "object":
            additional_props = field_schema.get("additionalProperties")
            if "properties" in field_schema or additional_props is False:
                return build_model(field_name, field_schema)
            value_type = (
                resolve_extra_value_type(additional_props, f"{field_name}_value")
                if isinstance(additional_props, dict)
                else typing.Any
            )
            return dict[str, value_type]  # type: ignore[valid-type]

        return TYPE_MAPPING.get(field_schema.get("type"), typing.Any)  # type: ignore[arg-type,return-value]

    def build_model(model_name: str, model_schema: dict) -> type[BaseModel]:
        fields = {}
        required = model_schema.get("required", [])
        for field_name, field_schema in model_schema.get("properties", {}).items():
            field_type = resolve_field_type(field_schema, f"{model_name}_{field_name}")
            field_params = __get_field_params_from_field_schema(field_schema)
            if field_name in required:
                # JSON Schema defaults are annotations, not permission to omit a
                # required property. Keep the annotation without supplying a value.
                if "default" in field_params:
                    field_params["json_schema_extra"] = {
                        "default": field_params.pop("default")
                    }
            elif "default" not in field_params:
                # Omission does not imply nullability. A factory allows omission
                # without adding a null default to the advertised JSON Schema.
                field_params["default_factory"] = lambda: None
            fields[field_name] = (field_type, Field(**field_params))

        config = {}
        if "additionalProperties" in model_schema:
            additional_props = model_schema["additionalProperties"]
            config["extra"] = "forbid" if additional_props is False else "allow"
            if isinstance(additional_props, dict):
                value_type = resolve_extra_value_type(
                    additional_props, f"{model_name}_extra"
                )
                fields["__pydantic_extra__"] = (
                    dict[str, value_type],
                    Field(init=False),
                )
        return create_model(
            model_name,
            **fields,
            __doc__=model_schema.get("description", ""),
            __config__=config,
        )

    for model_name, model_schema in definitions.items():
        models[model_name] = build_model(model_name, model_schema)
    # Definitions can refer to later definitions, including the type of an
    # additional property. Resolve them only after all model types exist.
    namespace = {definition_refs[name]: model for name, model in models.items()}
    for model in models.values():
        model.model_rebuild(_types_namespace=namespace)

    return build_model(name, schema)


def create_model_from_java_tool_schema_str(
    name: str, schema_str: str
) -> type[BaseModel]:
    """Create Pydantic model from a java tool input schema."""
    json_schema = json.loads(schema_str)
    properties = json_schema["properties"]

    fields = {}
    for param_name in properties:
        description = properties[param_name].get("description")
        if description is None:
            description = f"Parameter: {param_name}"
        type = TYPE_MAPPING.get(properties[param_name]["type"])
        fields[param_name] = (type, FieldInfo(description=description))
    return create_model(name, **fields)


def create_java_tool_schema_str_from_model(model: type[BaseModel]) -> str:
    """Create a java tool input schema string from a Pydantic model.

    This is the inverse function of create_model_from_java_tool_schema_str.

    Args:
        model: A Pydantic BaseModel class

    Returns:
        A JSON schema string compatible with Java tool input schema format
    """
    REVERSE_TYPE_MAPPING = {v: k for k, v in TYPE_MAPPING.items()}

    properties = {}
    required = []
    for field_name, field_info in model.model_fields.items():
        field_type = field_info.annotation

        origin = typing.get_origin(field_type)
        if origin is not None:
            if origin is typing.Union:
                args = typing.get_args(field_type)
                non_none_types = [arg for arg in args if arg is not type(None)]
                if non_none_types:
                    field_type = non_none_types[0]

        json_type = REVERSE_TYPE_MAPPING.get(field_type, "string")

        description = field_info.description
        if description is None:
            description = f"Parameter: {field_name}"

        properties[field_name] = {"type": json_type, "description": description}
        if field_info.is_required():
            required.append(field_name)

    json_schema: Dict[str, Any] = {"properties": properties}
    if required:
        json_schema["required"] = required

    return json.dumps(json_schema, ensure_ascii=False, indent=2)
